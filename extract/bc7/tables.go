// Interpolation weights by index bit count.
var weights2 = [...]int{0, 21, 43, 64}
var weights3 = [...]int{0, 9, 18, 27, 37, 46, 55, 64}
var weights4 = [...]int{0, 4, 9, 13, 17, 21, 26, 30, 34, 38, 43, 47, 51, 55, 60, 64}

func weightsFor(bits int) []int {
	switch bits {
	case 2:
		return weights2[:]
	case 3:
		return weights3[:]
	case 4:
		return weights4[:]
	}
	return nil
}


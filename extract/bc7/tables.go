// Per-mode configuration. Index = mode number (0..7).
type modeInfo struct {
	subsets        int // 1, 2, or 3 endpoint subsets
	partitionBits  int // bits for partition selector (0 if subsets == 1)
	rotationBits   int // modes 4, 5 only
	idxModeBits    int // mode 4 only: 1 if index selection bit is present
	colorBits      int // endpoint bits per R/G/B channel (before p-bit)
	alphaBits      int // endpoint bits for alpha (0 means opaque)
	pBitKind       int // 0=no pbits, 1=one pbit per endpoint, 2=one pbit shared per subset
	indexBits      int // primary index bits per pixel
	index2Bits     int // secondary index bits per pixel (modes 4, 5)
	colorEndpoints int // subsets * 2; precomputed for clarity
}

